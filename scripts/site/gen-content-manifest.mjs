#!/usr/bin/env node
/**
 * Build-time generator for the edge-middleware content manifest.
 *
 * Writes the TypeScript module middleware.ts imports (published Sanity
 * slugs + the shared Built to Work/Sell/Close/Run/Think/Multiply/Teach/See
 * route lists) so the edge middleware can decide which /blog, /guides and
 * /toolkit children are real (index) vs bogus (noindex) WITHOUT a runtime
 * Sanity call or a runtime file read.
 *
 * Wave B1: this module no longer fetches Sanity itself. The single Sanity
 * fetch for the whole build lives in `capture-content-snapshot.mjs`, which
 * imports `writeContentManifest()` from here and passes it the slugs it
 * already fetched. Running this file directly (`tsx gen-content-manifest.mjs`)
 * reads `.build/content-snapshot.json` instead, so it stays usable as a
 * standalone step if the snapshot already exists.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { BTW_CHAPTER_SLUGS, BTW_HUB_ROUTE } from './btw-seo-routes.mjs';
import { BTS_CHAPTER_SLUGS, BTS_HUB_ROUTE } from './bts-seo-routes.mjs';
import { BTC_CHAPTER_SLUGS, BTC_HUB_ROUTE } from './btc-seo-routes.mjs';
import { BTR_CHAPTER_SLUGS, BTR_HUB_ROUTE } from './btr-seo-routes.mjs';
import { BTT_CHAPTER_SLUGS, BTT_HUB_ROUTE } from './btt-seo-routes.mjs';
import { BTM_CHAPTER_SLUGS, BTM_HUB_ROUTE } from './btm-seo-routes.mjs';
import { BTE_CHAPTER_SLUGS, BTE_HUB_ROUTE } from './bte-seo-routes.mjs';
import { BSE_CHAPTER_SLUGS, BSE_HUB_ROUTE } from './bse-seo-routes.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../..');
const OUT_PATH = path.join(ROOT, 'src', 'generated', 'contentManifest.generated.ts');
const SNAPSHOT_PATH = path.join(ROOT, '.build', 'content-snapshot.json');

function uniqueSorted(values) {
  return [...new Set(values.filter((v) => typeof v === 'string' && v.length > 0))].sort();
}

function serialize(name, values) {
  const body = values.map((v) => `  ${JSON.stringify(v)},`).join('\n');
  return `export const ${name}: readonly string[] = [\n${body}\n]`;
}

/**
 * Pure: builds the manifest source from already-fetched slug lists. Exported
 * so `capture-content-snapshot.mjs` can call it with data from its single
 * Sanity fetch, with no second network round-trip.
 */
export function buildContentManifestSource({ posts, guides, toolkit }) {
  const blogSlugs = uniqueSorted(posts);
  const guideSlugs = uniqueSorted(guides);
  const toolkitSlugs = uniqueSorted(toolkit);
  const btwChapterSlugs = [...BTW_CHAPTER_SLUGS];
  const btsChapterSlugs = [...BTS_CHAPTER_SLUGS];
  const btcChapterSlugs = [...BTC_CHAPTER_SLUGS];
  const btrChapterSlugs = [...BTR_CHAPTER_SLUGS];
  const bttChapterSlugs = [...BTT_CHAPTER_SLUGS];
  const btmChapterSlugs = [...BTM_CHAPTER_SLUGS];
  const bteChapterSlugs = [...BTE_CHAPTER_SLUGS];
  const bseChapterSlugs = [...BSE_CHAPTER_SLUGS];

  const contents = `// AUTO-GENERATED by scripts/site/gen-content-manifest.mjs — DO NOT EDIT.
// Regenerated at the start of every build from the content snapshot's
// published Sanity slugs + the shared Built to Work / Built to Sell / Built
// to Close / Built to Run / Built to Think route lists. Bundled into the
// edge middleware so it can distinguish real content routes from bogus ones
// without a runtime lookup.

${serialize('BLOG_SLUGS', blogSlugs)}

${serialize('GUIDE_SLUGS', guideSlugs)}

${serialize('TOOLKIT_SLUGS', toolkitSlugs)}

${serialize('BTW_CHAPTER_SLUGS', btwChapterSlugs)}

export const BTW_HUB_ROUTE = ${JSON.stringify(BTW_HUB_ROUTE)}

${serialize('BTS_CHAPTER_SLUGS', btsChapterSlugs)}

export const BTS_HUB_ROUTE = ${JSON.stringify(BTS_HUB_ROUTE)}

${serialize('BTC_CHAPTER_SLUGS', btcChapterSlugs)}

export const BTC_HUB_ROUTE = ${JSON.stringify(BTC_HUB_ROUTE)}

${serialize('BTR_CHAPTER_SLUGS', btrChapterSlugs)}

export const BTR_HUB_ROUTE = ${JSON.stringify(BTR_HUB_ROUTE)}

${serialize('BTT_CHAPTER_SLUGS', bttChapterSlugs)}

export const BTT_HUB_ROUTE = ${JSON.stringify(BTT_HUB_ROUTE)}

${serialize('BTM_CHAPTER_SLUGS', btmChapterSlugs)}

export const BTM_HUB_ROUTE = ${JSON.stringify(BTM_HUB_ROUTE)}

${serialize('BTE_CHAPTER_SLUGS', bteChapterSlugs)}

export const BTE_HUB_ROUTE = ${JSON.stringify(BTE_HUB_ROUTE)}

${serialize('BSE_CHAPTER_SLUGS', bseChapterSlugs)}

export const BSE_HUB_ROUTE = ${JSON.stringify(BSE_HUB_ROUTE)}
`;

  return {
    contents,
    counts: {
      blog: blogSlugs.length,
      guides: guideSlugs.length,
      toolkit: toolkitSlugs.length,
      btw: btwChapterSlugs.length,
      bts: btsChapterSlugs.length,
      btc: btcChapterSlugs.length,
      btr: btrChapterSlugs.length,
      btt: bttChapterSlugs.length,
      btm: btmChapterSlugs.length,
      bte: bteChapterSlugs.length,
      bse: bseChapterSlugs.length,
    },
  };
}

/** Writes the manifest file from already-fetched slug lists; returns the counts logged by callers. */
export async function writeContentManifest({ posts, guides, toolkit }) {
  const { contents, counts } = buildContentManifestSource({ posts, guides, toolkit });
  await writeFile(OUT_PATH, contents, 'utf8');
  return counts;
}

async function main() {
  let snapshot;
  try {
    snapshot = JSON.parse(await readFile(SNAPSHOT_PATH, 'utf8'));
  } catch (err) {
    console.error(
      `[gen-content-manifest] No content snapshot at ${path.relative(ROOT, SNAPSHOT_PATH)}. ` +
        `Run capture-content-snapshot.mjs first.`
    );
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }

  const posts = (snapshot.posts ?? []).map((p) => p.slug);
  const guides = (snapshot.guides ?? []).map((g) => g.slug);
  const toolkit = (snapshot.toolkitItems ?? []).map((t) => t.slug);

  const counts = await writeContentManifest({ posts, guides, toolkit });
  console.log(
    `[gen-content-manifest] Wrote ${path.relative(ROOT, OUT_PATH)} ` +
      `(${counts.blog} blog, ${counts.guides} guides, ${counts.toolkit} toolkit, ${counts.btw} BTW chapters, ` +
      `${counts.bts} BTS chapters, ${counts.btc} BTC chapters, ${counts.btr} BTR chapters, ${counts.btt} BTT chapters, ` +
      `${counts.btm} BTM chapters, ${counts.bte} BTE chapters, ${counts.bse} BSE chapters).`
  );
}

const isMain = import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  main().catch((err) => {
    console.error('[gen-content-manifest] Fatal error:', err);
    process.exit(1);
  });
}
